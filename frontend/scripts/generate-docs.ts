/**
 * Regenerates the documents that are derived from code, so they cannot drift from it:
 *   docs/TEST_CASES.md    from the evaluation fixtures
 *   docs/API_EXAMPLES.md  real objects produced by the mock adapter and the runner
 * Run with: npm run docs:generate
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MockExecutiveDesk } from '../src/harness/mock/mockAdapter';
import { SUITES, getCase } from '../src/evaluation/fixtures';
import { renderFeatureStatus } from '../src/lib/featureStatus';
import { renderCasesMarkdown } from '../src/evaluation/fixtures/markdown';
import { runCase } from '../src/evaluation/runner';

const docs = resolve(dirname(fileURLToPath(import.meta.url)), '../../docs/frontend');
mkdirSync(docs, { recursive: true });

const block = (value: unknown) => `\`\`\`json\n${JSON.stringify(value, null, 2)}\n\`\`\``;

async function examples(): Promise<string> {
  const desk = new MockExecutiveDesk({ stepDelayMs: 0 });
  await desk.whenIdle();

  const requests = await desk.listRequests();
  const fresh = requests.find((r) => r.status === 'received')!;
  const waiting = requests.find((r) => r.id === 'req-001')!;
  const run = await desk.getRun(waiting.runIds[0]);
  const [pending] = await desk.listApprovals({ runId: run.id });

  const done = requests.find((r) => r.id === 'req-008')!;
  const doneRun = await desk.getRun(done.runIds[0]);
  const [approved] = await desk.listApprovals({ runId: doneRun.id });

  const [conversation] = await desk.listConversations();
  const messages = await desk.listMessages(conversation.id);

  const testCase = getCase('EVAL-003');
  const result = await runCase(new MockExecutiveDesk({ stepDelayMs: 0, seed: false }), testCase, { pollIntervalMs: 1 });
  // Wall-clock values differ on every run; pin them so regenerating does not churn the file.
  result.timing = { startedAt: '2026-11-13T18:00:00.000Z', finishedAt: '2026-11-13T18:00:00.000Z', wallClockMs: 0, agentReportedMs: null };

  return [
    '# API examples',
    '',
    '<!-- Generated by `npm run docs:generate` from the mock adapter. Do not edit by hand. -->',
    '',
    'Real objects taken from the mock adapter, to show the exact JSON the frontend expects. Field meanings are in [API_CONTRACT.md](API_CONTRACT.md). All data is synthetic. `usage` and every duration are null because the mock calls no model and does no real work; a real backend fills them in.',
    '',
    '## SecretaryRequest',
    '',
    'Just received, not yet processed:',
    '',
    block(fresh),
    '',
    'After triage, waiting for approval:',
    '',
    block(waiting),
    '',
    '## AgentRun',
    '',
    'Paused at an approval gate. `actions` holds AgentAction objects; the two side-effect actions are registered but have not run.',
    '',
    block(run),
    '',
    '## AgentAction',
    '',
    'A side-effect action after it ran (taken from a completed run):',
    '',
    block(doneRun.actions.find((a) => a.tool === 'calendar.create_event')),
    '',
    '## ApprovalRequest',
    '',
    'Pending:',
    '',
    block(pending),
    '',
    'Approved and executed (`changes` omitted here for length):',
    '',
    block({ ...approved, changes: '(same shape as above)' }),
    '',
    '## ConversationMessage',
    '',
    block(messages),
    '',
    '## EvaluationCase',
    '',
    block(testCase),
    '',
    '## EvaluationResult',
    '',
    'The same case scored against the scripted mock. `run` and `approvals` (the full trace) are omitted here for length.',
    '',
    block({ ...result, run: '(AgentRun, as above)', approvals: '(ApprovalRequest[], as above)' }),
    '',
  ].join('\n');
}

writeFileSync(resolve(docs, 'TEST_CASES.md'), renderCasesMarkdown(SUITES.desk.cases, 'desk'));
writeFileSync(resolve(docs, 'TEST_CASES_SCHEDULING.md'), renderCasesMarkdown(SUITES.scheduling.cases, 'scheduling'));
writeFileSync(resolve(docs, 'FEATURE_STATUS.md'), renderFeatureStatus());
writeFileSync(resolve(docs, 'API_EXAMPLES.md'), await examples());
console.log('Wrote docs/frontend/TEST_CASES*.md, FEATURE_STATUS.md and API_EXAMPLES.md');
