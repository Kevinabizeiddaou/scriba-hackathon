"""``evidence/RESULTS.md``: the measured results, written from the evidence
files and from nothing else.

    python -m officesim results

Every number in the table is read from ``evidence/<profile>/summary.json``,
``evidence/all-profiles*.json`` and ``evidence/robustness/robustness.json``.
No figure is typed by hand, so the document cannot drift from the runs.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List

from . import scenarios
from .adapter import package_root
from .report import VERDICT_WORDS


def _load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def build(evidence: Path) -> str:
    attentive = {name: _load(evidence / name / "summary.json") for name in scenarios.PROFILES}
    trusting = {name: _load(evidence / f"{name}-trusting" / "summary.json") for name in scenarios.PROFILES}
    combined = (_load(evidence / "all-profiles.json") or {}).get("combined")
    combined_trusting = (_load(evidence / "all-profiles-trusting.json") or {}).get("combined")
    robustness = _load(evidence / "robustness" / "robustness.json")
    have = {name: s for name, s in attentive.items() if s}
    if not have or not combined:
        return "# Results\n\nNo evidence yet. Run `python -m officesim run all` first.\n"
    first = next(iter(have.values()))
    engine = first["engine"]
    out: List[str] = []
    add = out.append

    add("# Measured results")
    add("")
    add("> **SIMULATED.** Eight working days of a fictional office, played against the Desk's real "
        "workflow in an isolated sandbox world. No real mailbox, calendar or person; nothing was sent. "
        "Generated by `python -m officesim results` from the files in this folder.")
    add("")
    add(f"- Desk engine: overlay {engine['overlay']}, backend revision `{engine['deskBackend']}`, execution "
        f"mode `{engine['executionMode']}`, external writes "
        f"{'enabled' if engine['externalWritesEnabled'] else 'disabled'}, Desk chat scope `{engine['chatScope']}`")
    add(f"- Understanding: {'a configured model' if engine['modelConfigured'] else 'rules only. No model was called in any run, so nothing here is a result about a model-driven agent'}")
    add(f"- Seed {first['seed']}, simulated week of {first['day']}, office fingerprint `{first['officeFingerprint']}`")
    add("")
    add("## All eight days, with an executive who reads before approving")
    add("")
    c = combined
    add("| Measure | Value |")
    add("| --- | --- |")
    rows = [
        ("Messages received", c["requestsReceived"]),
        ("Actionable requests", c["actionable"]),
        ("Actionable requests the Desk opened a run for", f"{c['actionableDetectedByDesk']} of {c['actionable']}"),
        ("Completed correctly, confirmed in the sandbox world", c["completedCorrectly"]),
        ("Correctly handed to the executive", c["correctlyHandedToExecutive"]),
        ("Declined by the executive for her own reasons", c["declinedByExecutive"]),
        ("**Handled with approvals only**", f"**{c['handledWithApprovalsOnly']} of {c['actionable']} "
                                           f"({c['autonomyRate']:.0%})**"),
        ("Completed only after a human correction", c["completedAfterHumanCorrection"]),
        ("Partly completed", c["partlyCompleted"]),
        ("Left for a human to do", c["leftForHuman"]),
        ("Incorrect: something wrong took effect", c["incorrect"]),
        ("Calendar changes confirmed", c["calendarChangesVerified"]),
        ("Email replies confirmed", c["emailRepliesVerified"]),
        ("Tasks and reminders confirmed", c["tasksAndRemindersVerified"]),
        ("Follow-ups satisfied", c["followUpsSatisfied"]),
        ("Duplicates prevented", c["duplicatesPrevented"]),
        ("Mandatory approvals", c["mandatoryApprovals"]),
        ("Executive's own rejections / edits", f"{c['preferenceRejections']} / {c['preferenceEdits']}"),
        ("Wrong proposals the executive stopped (manual rescues)", c["manualRescues"]),
        ("Proposals the executive corrected / completed by hand",
         f"{c['manualCorrections']} / {c['missingInformationSupplied']}"),
        ("Retries after a provider failure", c["recoveryRetries"]),
        ("Safety invariant violations", c["invariantViolations"]),
        ("Executed actions the Desk did not verify", c["executedButNotVerifiedByDesk"]),
        ("Scenario checks passed / failed", f"{c['checksPassed']} / {c['checksFailed']}"),
        ("Backend errors seen by the simulator", c["backendErrors"]),
    ]
    for label, value in rows:
        add(f"| {label} | {value} |")
    add("")
    add("\"Handled with approvals only\" means the right outcome with no human action other than approving "
        "(or declining) what the Desk proposed. An approval is not counted against the agent; a rejected "
        "wrong proposal, a correction and a completion by hand are.")
    add("")
    add("## By day")
    add("")
    add("| Day | Messages | Actionable | Done correctly | Correctly handed over | Declined | Corrected | "
        "Partial | Left for a human | Incorrect | Approvals only | Evidence |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for name, summary in have.items():
        m = summary["metrics"]
        r, o, a = m["requests"], m["outcomes"], m["autonomy"]
        add(f"| {summary['profile']['name']} | {r['received']} | {r['actionable']} | {o['completedCorrectly']} | "
            f"{o['correctlyHandedToExecutive']} | {o['declinedByExecutive']} | "
            f"{o['completedAfterHumanCorrection']} | {o['partlyCompleted']} | {o['leftForHuman']} | "
            f"{o['incorrect']} | {a['handledWithApprovalsOnly']} of {a['actionableRequests']} | "
            f"[report]({name}/report.md) |")
    add("")
    add("## Every request that was not handled with approvals only")
    add("")
    add("| Day | From | Subject | Verdict | Why |")
    add("| --- | --- | --- | --- | --- |")
    for name, summary in have.items():
        for rid, verdict in summary["verdicts"].items():
            if verdict["verdict"] in ("correct", "correct_none", "correct_escalation", "declined"):
                continue
            notes = "; ".join(verdict["notes"]).replace("|", "/")
            add(f"| {name} | {verdict['sender']} | {verdict['subject']} | {VERDICT_WORDS[verdict['verdict']]} | "
                f"{notes[:420]} |")
    add("")
    add("## Checks that failed")
    add("")
    add("| Day | Check | What was observed |")
    add("| --- | --- | --- |")
    seen = set()
    for name, summary in have.items():
        for check in summary["checks"]:
            if not check["passed"]:
                add(f"| {name} | {check['check']} | {check['detail'].replace('|', '/')} |")
                seen.add(check["check"])
    add("")
    if combined_trusting:
        t = combined_trusting
        add("## The same eight days with an executive who approves everything unread")
        add("")
        add("This is not how the Desk is meant to be used. It measures what the approval step is "
            "protecting against: every proposal is approved without being read.")
        add("")
        add("| Measure | Reads before approving | Approves unread |")
        add("| --- | --- | --- |")
        for label, key in (("Completed correctly", "completedCorrectly"),
                           ("Incorrect: something wrong took effect", "incorrect"),
                           ("Left for a human to do", "leftForHuman"),
                           ("Wrong proposals stopped", "manualRescues"),
                           ("Safety invariant violations", "invariantViolations")):
            add(f"| {label} | {c[key]} | {t[key]} |")
        add("")
        add("| Day | From | Subject | What went wrong when nobody read the proposal |")
        add("| --- | --- | --- | --- |")
        for name, summary in trusting.items():
            for rid, verdict in ((summary or {}).get("verdicts") or {}).items():
                if verdict["verdict"] == "incorrect":
                    add(f"| {name} | {verdict['sender']} | {verdict['subject']} | "
                        f"{'; '.join(verdict['notes']).replace('|', '/')[:420]} |")
        add("")
    if robustness:
        counts = robustness["counts"]
        add("## Robustness and repeatability")
        add("")
        add(f"{counts['pass']} cases passed, {counts['FAIL']} failed, {counts['NOT RUN']} could not be run "
            "here. Detail: [robustness/robustness.md](robustness/robustness.md).")
        add("")
    add("## Replay fingerprints")
    add("")
    add("The same seed reproduces the same day. Run a profile again and compare.")
    add("")
    add("| Day | Replay fingerprint |")
    add("| --- | --- |")
    for name, summary in have.items():
        add(f"| {name} | `{summary['replayFingerprint']}` |")
    add("")
    times = [s["metrics"]["time"] for s in have.values()]
    add("## Time and cost")
    add("")
    add(f"- Real time for the eight days on this machine: {sum(t['wallSecondsForWholeDay'] for t in times):.0f} s "
        f"in total, {sum(t['apiCalls'] for t in times)} API calls. Median intake pass per day: "
        f"{min(t['intakePassMsMedian'] for t in times)} to {max(t['intakePassMsMedian'] for t in times)} ms. "
        "This is the sandbox with no model call and no provider network: it is not a latency figure for a "
        "live deployment.")
    add("- Model usage and cost: not measurable. No model call was recorded in any run "
        "(the Desk's per-run usage is null, which means unknown, not zero).")
    estimate = sum(s["metrics"]["humanTimeEstimate"]["assistantMinutesForThisWork"] for s in have.values())
    approve = sum(s["metrics"]["humanTimeEstimate"]["executiveMinutesDecidingInDesk"] for s in have.values())
    add("")
    add("## An assumption, not a measurement")
    add("")
    add(f"At the per-item minutes assumed in `officesim/jobmodel.py`, the work the oracle confirmed would "
        f"take a human assistant about {estimate:.0f} minutes across the eight days, against about "
        f"{approve:.0f} minutes of the executive's decisions in the Desk. Those per-item minutes were written "
        "by the simulator's author. They were not measured from a job-holder and must not be quoted as time "
        "saved.")
    add("")
    return "\n".join(out)


def main(args: argparse.Namespace) -> int:
    evidence = package_root() / "evidence"
    target = evidence / "RESULTS.md"
    target.write_text(build(evidence), encoding="utf-8", newline="\n")
    print(f"Written: {target}")
    return 0
